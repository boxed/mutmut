import json
from collections.abc import Mapping
from collections.abc import Sequence
from dataclasses import astuple
from dataclasses import dataclass
from itertools import islice
from pathlib import Path


@dataclass(frozen=True)
class LineSpan:
    """A range of lines in a file, 1-based and inclusive on both ends."""

    start: int
    end: int


@dataclass(frozen=True)
class SourceSpan:
    """A range of code in a source file, as libcst reports it.

    Lines are 1-based and columns 0-based. The end column is exclusive."""

    start_line: int
    start_column: int
    end_line: int
    end_column: int

    def contains(self, other: "SourceSpan") -> bool:
        starts_before = (self.start_line, self.start_column) <= (other.start_line, other.start_column)
        ends_after = (other.end_line, other.end_column) <= (self.end_line, self.end_column)
        return starts_before and ends_after


class MutantLineSpans:
    """Index of the lines each generated function occupies in a mutated file.

    Mutated files are much bigger than the sources they were generated from, so parsing one
    just to display a single mutant is slow and memory hungry. This index is written when the
    mutants are generated, which lets us read one function out of a mutated file without
    parsing it at all.
    """

    format_version = 1

    def __init__(self, *, path: Path | str, span_by_function_name: Mapping[str, LineSpan]) -> None:
        self.path = path
        self.mutants_path = Path("mutants") / str(path)
        self.index_path = Path("mutants") / (str(path) + ".spans")
        self.span_by_function_name = span_by_function_name

    @classmethod
    def load(cls, path: Path | str) -> "MutantLineSpans | None":
        """Read the index for `path`, or return None if there is none we understand.

        Mutants generated by an older version of mutmut have no index, and callers are
        expected to fall back to parsing the mutated file in that case.
        """
        index = cls(path=path, span_by_function_name={})
        try:
            with open(index.index_path) as f:
                data = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            return None

        if data.get("version") != cls.format_version:
            return None

        index.span_by_function_name = {name: LineSpan(start, end) for name, (start, end) in data["spans"].items()}
        return index

    def save(self) -> None:
        with open(self.index_path, "w") as f:
            json.dump(
                {
                    "version": self.format_version,
                    "spans": {name: [span.start, span.end] for name, span in self.span_by_function_name.items()},
                },
                f,
            )

    def read_function_sources(self, function_names: Sequence[str]) -> list[str]:
        """Read the source of the named generated functions out of the mutated file.

        The source is returned exactly as it appears in the file, so the source of a method is
        still indented. Raises KeyError if a name is not in the index.
        """
        spans = [self.span_by_function_name[name] for name in function_names]
        return read_line_spans(self.mutants_path, spans)


def read_line_spans(file_path: Path | str, spans: Sequence[LineSpan]) -> list[str]:
    """Read the given line spans from a file in a single forward pass.

    The spans may be given in any order, but they must not overlap.
    """
    sources: list[str] = [""] * len(spans)

    with open(file_path) as f:
        line_number = 1
        for i in sorted(range(len(spans)), key=lambda i: spans[i].start):
            span = spans[i]
            if span.start < line_number:
                raise ValueError(f"Overlapping spans in {file_path}: {spans}")

            # skip forward to the start of the span, then read it
            for _ in islice(f, span.start - line_number):
                pass
            sources[i] = "".join(islice(f, span.end - span.start + 1))
            line_number = span.end + 1

    return sources


class SourceFileMutationData:
    def __init__(self, *, path: Path | str) -> None:
        self.estimated_time_of_tests_by_mutant: dict[str, float] = {}
        self.path = path
        self.meta_path = Path("mutants") / (str(path) + ".meta")
        self.exit_code_by_key: dict[str, int | None] = {}
        self.hash_by_function_name: dict[str, str] = {}
        self.durations_by_key: dict[str, float] = {}
        self.type_check_error_by_key: dict[str, str | None] = {}
        #: The code in the source file that each mutant changes
        self.source_span_by_key: dict[str, SourceSpan] = {}
        #: The code that mutants like `a = b` -> `a = None` remove, see `shadowed_by_key`
        self.removed_span_by_key: dict[str, SourceSpan] = {}

    def load(self) -> None:
        try:
            with open(self.meta_path) as f:
                meta = json.load(f)
        except FileNotFoundError:
            return

        self.exit_code_by_key = meta.pop("exit_code_by_key")
        self.hash_by_function_name = meta.pop("hash_by_function_name", {})
        self.type_check_error_by_key = meta.pop("type_check_error_by_key", {})
        self.durations_by_key = meta.pop("durations_by_key")
        self.estimated_time_of_tests_by_mutant = meta.pop("estimated_durations_by_key")
        self.source_span_by_key = {k: SourceSpan(*v) for k, v in meta.pop("source_span_by_key", {}).items()}
        self.removed_span_by_key = {k: SourceSpan(*v) for k, v in meta.pop("removed_span_by_key", {}).items()}
        assert not meta, f"Meta file {self.meta_path} constains unexpected keys: {set(meta.keys())}"

    def save(self) -> None:
        with open(self.meta_path, "w") as f:
            json.dump(
                {
                    "exit_code_by_key": self.exit_code_by_key,
                    "hash_by_function_name": self.hash_by_function_name,
                    "type_check_error_by_key": self.type_check_error_by_key,
                    "durations_by_key": self.durations_by_key,
                    "estimated_durations_by_key": self.estimated_time_of_tests_by_mutant,
                    "source_span_by_key": {k: astuple(v) for k, v in self.source_span_by_key.items()},
                    "removed_span_by_key": {k: astuple(v) for k, v in self.removed_span_by_key.items()},
                },
                f,
                indent=4,
            )

    def shadowed_by_key(self) -> dict[str, str]:
        """Find the mutants that are shadowed by a surviving mutant that removes their code.

        If the tests do not notice that `x = foo(a + 1)` became `x = None`, the mutants inside
        `foo(a + 1)` are not worth looking at on their own. Fixing the tests for the mutant that
        removes the code is likely to deal with them too.

        :return: The outermost surviving mutant that shadows each shadowed mutant."""
        # exit code 0 means the mutant survived
        shadowing_keys = [key for key in self.removed_span_by_key if self.exit_code_by_key.get(key) == 0]

        def outermost_first(key: str) -> tuple[int, int, int, int]:
            # the removed spans that contain a mutant are nested in each other
            span = self.removed_span_by_key[key]
            return span.start_line, span.start_column, -span.end_line, -span.end_column

        shadowing_keys.sort(key=outermost_first)

        shadowed_by_key: dict[str, str] = {}
        for key, span in self.source_span_by_key.items():
            for shadowing_key in shadowing_keys:
                if key != shadowing_key and self.removed_span_by_key[shadowing_key].contains(span):
                    shadowed_by_key[key] = shadowing_key
                    break
        return shadowed_by_key

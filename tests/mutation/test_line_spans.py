"""Tests for the line span index that lets us read a single function out of a mutated file."""

from pathlib import Path

import libcst as cst
import pytest
from libcst.metadata import MetadataWrapper
from libcst.metadata import WhitespaceInclusivePositionProvider

from mutmut.mutation.data import LineSpan
from mutmut.mutation.data import MutantLineSpans
from mutmut.mutation.data import read_line_spans
from mutmut.mutation.file_mutation import mutate_file_contents

TRICKY_SOURCE = '''\
# a comment above everything
import functools


@functools.cache
async def fetch(x=1):
    return x + 1


# a comment about the class
class Thing(
    dict,
):
    """A docstring mentioning def fetch( in passing."""

    @property
    def timeout(self):
        return 30

    def multiline(
        self,
        a=1,
    ):
        return a + 2

    def with_unindented_string(self):
        text = """
def multiline(
"""
        return text + str(3)
'''


def spans_from_libcst(code: str) -> dict[str, tuple[int, int]]:
    """Get the line span of every function in `code`, according to libcst itself."""
    module = cst.parse_module(code)
    positions = MetadataWrapper(module, unsafe_skip_copy=True).resolve(WhitespaceInclusivePositionProvider)

    spans = {}
    for node, position in positions.items():
        if not isinstance(node, cst.FunctionDef):
            continue
        # libcst's whitespace inclusive end includes the trailing newline, which puts it on the
        # next line, while our spans end on the last line that has content
        end_line = position.end.line - 1 if position.end.column == 0 else position.end.line
        spans[node.name.value] = (position.start.line, end_line)
    return spans


@pytest.mark.parametrize(
    "source",
    [
        pytest.param("def f():\n    return 1\n", id="single function"),
        pytest.param("def f():\n    return 1", id="no trailing newline"),
        pytest.param("# leading comment\n\n\ndef f():\n    return 1\n", id="leading comments"),
        pytest.param("class C:\n    def m(self):\n        return 1\n", id="method"),
        pytest.param("class C:\n\tdef m(self):\n\t\treturn 1\n", id="tabs"),
        pytest.param("def f():\r\n    return 1\r\n", id="crlf"),
        pytest.param("class Klaß:\n    def méthod(self):\n        return 1\n", id="non-ascii names"),
        pytest.param("def f():\n    return 1\n\n\n# trailing comment\n", id="trailing comment"),
        pytest.param(TRICKY_SOURCE, id="tricky"),
    ],
)
def test_line_spans_match_the_generated_code(source: str):
    mutated_file = mutate_file_contents("test.py", source)

    assert mutated_file.line_span_by_function_name, "expected at least one mutant"
    assert mutated_file.line_span_by_function_name.keys() <= spans_from_libcst(mutated_file.code).keys()

    expected = spans_from_libcst(mutated_file.code)
    for name, span in mutated_file.line_span_by_function_name.items():
        assert (span.start, span.end) == expected[name], f"wrong span for {name}"


def test_line_spans_cover_both_the_mutants_and_the_original(tmp_path: Path):
    mutated_file = mutate_file_contents("test.py", "def f():\n    return 1\n")

    names = set(mutated_file.line_span_by_function_name)
    assert "x_f__mutmut_orig" in names
    assert names == {"x_f__mutmut_orig", *mutated_file.mutant_names}


def test_read_function_sources(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    source = "class C:\n    def m(self):\n        return 1\n"
    mutated_file = mutate_file_contents("test.py", source)

    monkeypatch.chdir(tmp_path)
    (tmp_path / "mutants").mkdir()
    (tmp_path / "mutants" / "test.py").write_text(mutated_file.code)
    line_spans = MutantLineSpans(path="test.py", span_by_function_name=mutated_file.line_span_by_function_name)
    line_spans.save()

    loaded = MutantLineSpans.load("test.py")
    assert loaded is not None
    assert loaded.span_by_function_name == dict(mutated_file.line_span_by_function_name)

    (orig, mutant) = loaded.read_function_sources(["xǁCǁm__mutmut_orig", "xǁCǁm__mutmut_1"])
    # methods are read as they appear in the file, so they are still indented
    assert orig == "    def xǁCǁm__mutmut_orig(self):\n        return 1\n"
    assert mutant == "    def xǁCǁm__mutmut_1(self):\n        return 2\n"

    with pytest.raises(KeyError):
        loaded.read_function_sources(["x_does_not_exist__mutmut_1"])


def test_load_returns_none_without_a_usable_index(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "mutants").mkdir()

    # mutants generated by an older version of mutmut have no index at all
    assert MutantLineSpans.load("test.py") is None

    (tmp_path / "mutants" / "test.py.spans").write_text("this is not json")
    assert MutantLineSpans.load("test.py") is None

    (tmp_path / "mutants" / "test.py.spans").write_text('{"version": 999, "spans": {}}')
    assert MutantLineSpans.load("test.py") is None


def test_a_stale_index_is_ignored(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    """An index that does not match the mutated file must not produce a bogus result."""
    from mutmut.__main__ import read_functions_from_index

    source = "def f():\n    return 1\n"
    mutated_file = mutate_file_contents("test.py", source)

    monkeypatch.chdir(tmp_path)
    (tmp_path / "mutants").mkdir()
    (tmp_path / "mutants" / "test.py").write_text(mutated_file.code)

    names = ["x_f__mutmut_orig", "x_f__mutmut_1"]
    stale_spans = [
        # spans pointing at lines that are not a function at all
        dict.fromkeys(names, LineSpan(1, 3)),
        {name: LineSpan(i * 2 + 1, i * 2 + 2) for i, name in enumerate(names)},
        # a span for the mutant, but not for the function it mutates
        {"x_f__mutmut_1": mutated_file.line_span_by_function_name["x_f__mutmut_1"]},
    ]
    for span_by_function_name in stale_spans:
        MutantLineSpans(path="test.py", span_by_function_name=span_by_function_name).save()
        assert read_functions_from_index("test.x_f__mutmut_1", "test.py") is None

    # and with a good index it does find the functions
    MutantLineSpans(path="test.py", span_by_function_name=mutated_file.line_span_by_function_name).save()
    assert read_functions_from_index("test.x_f__mutmut_1", "test.py") is not None


def test_read_line_spans(tmp_path: Path):
    path = tmp_path / "lines.txt"
    path.write_text("".join(f"line {i}\n" for i in range(1, 11)))

    assert read_line_spans(path, [LineSpan(1, 2)]) == ["line 1\nline 2\n"]
    assert read_line_spans(path, [LineSpan(10, 10)]) == ["line 10\n"]

    # several spans are read in one pass, in whatever order they are given
    assert read_line_spans(path, [LineSpan(9, 10), LineSpan(2, 3)]) == ["line 9\nline 10\n", "line 2\nline 3\n"]

    with pytest.raises(ValueError):
        read_line_spans(path, [LineSpan(1, 5), LineSpan(3, 6)])
